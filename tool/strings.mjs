const keys = new Set();
const en = { '@@locale': 'en' };
const hi = { '@@locale': 'hi' };
for (const [key, e, h, placeholders] of S) {
  if (keys.has(key)) throw new Error(`Duplicate key: ${key}`);
  keys.add(key);
  en[key] = e;
  hi[key] = h;
  const names = [...e.matchAll(/\{(\w+)\}/g)].map((m) => m[1]);
  for (const n of [...h.matchAll(/\{(\w+)\}/g)].map((m) => m[1])) {
    if (!names.includes(n)) throw new Error(`${key}: Hindi uses {${n}} which English does not`);
  }
  if (names.length) {
    if (!placeholders) throw new Error(`${key}: missing placeholder types`);
    en[`@${key}`] = {
      placeholders: Object.fromEntries(names.map((n) => [n, { type: placeholders[n] ?? 'String' }])),
    };
  }
}
const out = new URL('../lib/l10n/', import.meta.url);
writeFileSync(new URL('app_en.arb', out), JSON.stringify(en, null, 2) + '\n');
writeFileSync(new URL('app_hi.arb', out), JSON.stringify(hi, null, 2) + '\n');
console.log(`Wrote ${keys.size} strings in English and Hindi.`);
